"""FSM состояния для опросника.

Модуль определяет состояния конечного автомата (FSM) для процесса
прохождения опросника пользователем согласно CJM.
"""
from aiogram.fsm.state import State, StatesGroup


class SurveyStates(StatesGroup):
    """Состояния опросника согласно CJM.
    
    Определяет последовательность состояний для прохождения опросника:
    1. Согласие на обработку ПД
    2. 5 базовых вопросов (пол, возраст, имя, ценности, сферы)
    3. 5 развернутых вопросов от GPT
    4. Выбор ролевой модели
    5. Цель на 3 месяца
    6. Генерация роадмапа
    7. Завершение опроса
    
    Attributes:
        privacy_consent (State): Состояние ожидания согласия на обработку персональных данных
        gender (State): Состояние ответа на вопрос о поле
        age (State): Состояние ответа на вопрос о возрасте
        name (State): Состояние ответа на вопрос об имени
        values (State): Состояние выбора 3 ценностей
        development_spheres (State): Состояние выбора сфер развития
        detailed_questions (State): Состояние ответов на 5 развернутых вопросов от GPT
        role_model (State): Состояние выбора ролевой модели
        goal_3months (State): Состояние ввода цели на 3 месяца
        roadmap_generation (State): Состояние генерации роадмапа
        finish (State): Состояние завершения опроса
        restart_confirmation (State): Состояние подтверждения рестарта бота
    """
    privacy_consent = State()
    """Состояние ожидания согласия на обработку персональных данных."""
    
    gender = State()
    """Состояние ответа на вопрос о поле (Мужской/Женский)."""
    
    age = State()
    """Состояние ответа на вопрос о возрасте (текстовый ввод)."""
    
    name = State()
    """Состояние ответа на вопрос об имени (текстовый ввод)."""
    
    values = State()
    """Состояние выбора 3 основных ценностей."""
    
    development_spheres = State()
    """Состояние выбора сфер развития (можно выбрать несколько)."""
    
    detailed_questions = State()
    """Состояние ответов на 5 развернутых вопросов от GPT."""
    
    role_model = State()
    """Состояние выбора ролевой модели."""
    
    goal_3months = State()
    """Состояние ввода цели на 3 месяца (текстовый ввод)."""
    
    roadmap_vision = State()
    """Состояние запроса видения роадмапа у пользователя (до генерации)."""
    
    roadmap_generation = State()
    """Состояние генерации роадмапа достижения цели."""
    
    roadmap_review = State()
    """Состояние проверки роадмапа - упустил ли что-то сервис."""
    
    roadmap_feedback = State()
    """Состояние получения пожеланий по улучшению роадмапа."""
    
    finish = State()
    """Состояние завершения опроса."""
    
    restart_confirmation = State()
    """Состояние подтверждения рестарта бота."""
    
    consultation = State()
    """Состояние свободной консультации - бот отвечает на вопросы пользователя."""
    
    personalization = State()
    """Состояние персонализации - бот задает глубокие вопросы для лучшего понимания пользователя."""
    
    promo_code = State()
    """Состояние ввода промокода для активации premium доступа."""

